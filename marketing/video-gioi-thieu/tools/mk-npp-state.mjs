import { chromium } from 'playwright';
import { rewriteApi } from './route-api.mjs';
const b = await chromium.launch({ channel: 'msedge' });
const ctx = await b.newContext({ viewport: { width: 1366, height: 768 }, locale: 'vi-VN' });
await rewriteApi(ctx);
const p = await ctx.newPage();
await p.goto('http://localhost:3072/', { waitUntil: 'load', timeout: 120000 }); await p.waitForTimeout(2500);
await p.locator('input').nth(0).fill('npp@eurohouse.vn'); await p.locator('input').nth(1).fill('Eurohouse@2026');
await p.getByRole('button', { name: 'Vào hệ thống' }).click();
await p.getByText('Tổng quan NPP').first().waitFor({ timeout: 90000 });
await ctx.storageState({ path: process.env.TEMP + '/eh-npp-state.json' }); console.log('saved', p.url());
await b.close();
