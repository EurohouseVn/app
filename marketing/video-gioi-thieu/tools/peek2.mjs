import { chromium } from 'playwright';
const state = process.argv[2];
const b = await chromium.launch({ channel: 'msedge' });
const ctx = await b.newContext({ storageState: state, viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, locale: 'vi-VN' });
const p = await ctx.newPage(); await p.goto('http://localhost:8095/orders', { waitUntil: 'load' }); await p.waitForTimeout(5000);
await p.getByText('Hệ 70 Ecento').first().click(); await p.waitForTimeout(1500);
await p.mouse.move(195, 500); await p.mouse.wheel(0, 700); await p.waitForTimeout(800);
await p.screenshot({ path: process.env.TEMP + '/eh-o2.png' });
console.log(await p.locator('input').evaluateAll(l => l.map(i => i.type + ':' + (i.placeholder || i.value))).then(a=>a.slice(0,20)));
await b.close();
